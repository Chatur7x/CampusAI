#!/usr/bin/env bash
# =============================================================
# Generate a reproducible dependency lock for the AI server.
#
# WHY THIS IS A SCRIPT AND NOT A COMMITTED LOCK FILE
# ai-server/requirements.txt uses `>=` ranges, so two builds months apart can
# resolve to different versions. Pinning needs the *target* environment, not a
# developer machine: the Docker image is python:3.12-slim-bookworm, while a
# typical local venv is a different Python and is missing insightface entirely
# (it needs to compile). A lock generated locally would therefore be fiction.
#
# So: build the real image, export pip freeze from it, and commit that.
#
# Usage:
#   bash scripts/pin-python-deps.sh              # writes ai-server/requirements.lock.txt
#   bash scripts/pin-python-deps.sh --check      # report drift, write nothing
#   bash scripts/pin-python-deps.sh --verify     # rebuild the image FROM the lock
#
# After generating, switch the Dockerfile to install from the lock:
#   COPY ai-server/requirements.lock.txt ./
#   RUN pip install -r requirements.lock.txt
# =============================================================
set -euo pipefail

cd "$(dirname "$0")/.."

IMAGE="aisms-ai:lockgen"
LOCK="ai-server/requirements.lock.txt"
MODE="${1:-}"

red()   { printf '\033[31m%s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }
dim()   { printf '\033[2m%s\033[0m\n' "$*"; }

command -v docker >/dev/null 2>&1 || { red "docker not found"; exit 1; }

if [[ "$MODE" == "--verify" ]]; then
  [[ -f "$LOCK" ]] || { red "no $LOCK — run without a flag first"; exit 1; }
  dim "verifying the image builds from $LOCK …"
  # Temporarily point the Dockerfile at the lock, build, then restore.
  cp ai-server/Dockerfile ai-server/Dockerfile.bak
  trap 'mv ai-server/Dockerfile.bak ai-server/Dockerfile' EXIT
  sed -i 's#COPY ai-server/requirements.txt ./#COPY ai-server/requirements.lock.txt ./#' ai-server/Dockerfile
  sed -i 's#-r requirements.txt#-r requirements.lock.txt#' ai-server/Dockerfile
  docker build -f ai-server/Dockerfile -t aisms-ai:lockverify .
  green "OK — the image installs cleanly from the lock."
  exit 0
fi

dim "building $IMAGE from the current requirements.txt (this compiles insightface, be patient) …"
docker build -f ai-server/Dockerfile --target builder -t "$IMAGE" .

dim "exporting resolved versions …"
FREEZE=$(docker run --rm --entrypoint sh "$IMAGE" -c \
  '/opt/venv/bin/pip freeze --exclude-editable | sort -f')

if [[ "$MODE" == "--check" ]]; then
  if [[ -f "$LOCK" ]]; then
    if diff <(printf '%s\n' "$FREEZE") <(sort -f "$LOCK") >/dev/null; then
      green "no drift — the image matches $LOCK"
      exit 0
    fi
    red "DRIFT between $LOCK and what the image currently resolves:"
    diff <(printf '%s\n' "$FREEZE") <(sort -f "$LOCK") || true
    exit 1
  fi
  red "no $LOCK yet — run without a flag to create it"
  exit 1
fi

{
  echo "# Generated by scripts/pin-python-deps.sh — do not hand-edit."
  echo "# Resolved inside the real python:3.12-slim-bookworm image."
  echo "# Regenerate and re-run the test suite whenever requirements.txt changes."
  printf '%s\n' "$FREEZE"
} > "$LOCK"

green "wrote $LOCK ($(printf '%s\n' "$FREEZE" | wc -l) packages)"
dim "now switch ai-server/Dockerfile to install from the lock, then:"
dim "  bash scripts/pin-python-deps.sh --verify"
